BEGIN = "<!-- BEGIN GENERATED LIST: edit data/*.json and run scripts/build.py -->"
END = "<!-- END GENERATED LIST -->"

GROUPS = [("learn", "Learn"), ("read", "Read"), ("watch", "Watch"), ("listen", "Listen")]
TYPE_ORDER = ["website", "app", "newsletter", "youtube", "bilibili", "podcast"]
TYPE_LABEL = {"website": "🌐 Websites", "app": "📱 Apps", "newsletter": "✉️ Newsletters",
              "youtube": "▶️ YouTube", "bilibili": "📺 Bilibili", "podcast": "🎧 Podcasts"}
SCRIPT_LABEL = {"simplified": "简", "traditional": "繁", "both": "简/繁"}
REGION_LABEL = {"cn": "CN", "tw": "TW", "hk": "HK", "sg": "SG", "my": "MY", "global": "Global"}


def gh_anchor(title):
    """GitHub's heading anchor: lowercase, drop punctuation, spaces to hyphens."""
    return re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")


def level_label(levels):
    if len(levels) == 3:
        return "All levels"
    names = [l.capitalize() for l in levels]
    return "–".join([names[0], names[-1]]) if len(names) > 1 else names[0]


def meta_parts(r):
    parts = []
    if r["for_learners"]:
        parts.append("🎓")
    parts.append(level_label(r["level"]))
    parts.append(SCRIPT_LABEL[r["script"]])
    parts.append(REGION_LABEL[r["region"]])
    if r["dialect"] == "cantonese":
        parts.append("粤语")
    if r["language"] != "zh":
        parts.append("EN" if r["language"] == "en" else "中/EN")
    if r["pricing"] != "free":
        parts.append(r["pricing"].capitalize())
    return parts


def by_type(items):
    groups = {}
    for r in items:
        groups.setdefault(r["type"], []).append(r)
    return [(t, groups[t]) for t in TYPE_ORDER if t in groups]


def md_escape(s):
    return s.replace("[", "\\[").replace("]", "\\]")


def render_markdown(cats, by_cat):
    total = sum(len(v) for v in by_cat.values())
    out = [BEGIN, "", "## Contents", ""]
    for gid, gname in GROUPS:
        gcats = [c for c in cats if c["group"] == gid]
        out.append(f"- [{gname}](#{gh_anchor(gname)})")
        for c in gcats:
            out.append(f"  - [{c['name']}](#{gh_anchor(c['name'])}) ({len(by_cat.get(c['id'], []))})")
    out += ["", f"**{total} resources.** Legend: 🎓 made for learners · 简 simplified · 繁 traditional · "
            "CN/TW/HK/SG/MY region · 中/EN bilingual · EN in English.", ""]

    for gid, gname in GROUPS:
        out += [f"## {gname}", ""]
        for c in (c for c in cats if c["group"] == gid):
            items = by_cat.get(c["id"], [])
            out += [f"### {c['name']}", "", f"{c['name_zh']} · {c['description']}", ""]
            for t, rs in by_type(items):
                out += [f"**{TYPE_LABEL[t]}**", ""]
                for r in rs:
                    out.append(f"- [{md_escape(r['name'])}]({r['url']}) - {r['description']} <sub>{' · '.join(meta_parts(r))}</sub>")
                out.append("")
            out += ["[⬆ back to contents](#contents)", ""]
    out.append(END)
    return "\n".join(out)


def splice_readme(current, generated):
    """Replace the generated block in README.md, keeping the hand-written text around it."""
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        return head + generated + rest.split(END, 1)[1]
    return current.rstrip() + "\n\n" + generated + "\n"


def render_html(cats, by_cat, data_version):
    esc = html.escape
    total = sum(len(v) for v in by_cat.values())
    nav, body = [], []
    for gid, gname in GROUPS:
        nav.append(f'<p class="g">{gname}</p>')
        body.append(f'<h2 class="group" id="{gid}">{gname}</h2>')
        for c in (c for c in cats if c["group"] == gid):
            items = by_cat.get(c["id"], [])
            nav.append(f'<a href="#{c["id"]}" data-nav="{c["id"]}">{esc(c["name"])} <span class="n">{len(items)}</span></a>')
            body.append(f'<section id="{c["id"]}" data-cat="{c["id"]}"><h3>{esc(c["name"])} <small>{esc(c["name_zh"])}</small>'
                        f' <span class="n" data-count>{len(items)}</span></h3><p class="cd">{esc(c["description"])}</p>')
            for t, rs in by_type(items):
                body.append(f'<div class="tg" data-type-group><h4>{esc(TYPE_LABEL[t])}</h4><ul>')
                for r in rs:
                    search = " ".join([r["name"], r["description"], " ".join(r["tags"]), r["id"]]).lower()
                    attrs = (f'data-type="{r["type"]}" data-level="{" ".join(r["level"])}" data-script="{r["script"]}" '
                             f'data-region="{r["region"]}" data-learner="{int(r["for_learners"])}" data-s="{esc(search)}"')
                    chips = "".join(f"<i>{esc(p)}</i>" for p in meta_parts(r))
                    body.append(f'<li {attrs}><a href="{esc(r["url"])}" target="_blank" rel="noopener">{esc(r["name"])}</a>'
                                f'<span class="d">{esc(r["description"])}</span><span class="m">{chips}</span></li>')
                body.append("</ul></div>")
            body.append("</section>")

    return HTML_TEMPLATE.format(
        total=total, ncats=len(cats), data_version=data_version, repo=REPO_URL,
        nav="\n".join(nav), body="\n".join(body),
    )


