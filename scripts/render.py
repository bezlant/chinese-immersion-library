"""Render the human-readable views of the data: the README list and the GitHub Pages site.

Both are generated by build.py; do not edit their output by hand.
Icons are Lucide (ISC), vendored in vendor/lucide/.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICON_DIR = ROOT / "vendor" / "lucide"
README_ICON_DIR = "assets/icons"
README_ICON_COLOR = "#8b949e"  # GitHub's muted grey, readable in light and dark themes

REPO_URL = "https://github.com/krmanik/chinese-immersion-library"
BEGIN = "<!-- BEGIN GENERATED LIST: edit data/*.json and run scripts/build.py -->"
END = "<!-- END GENERATED LIST -->"

GROUPS = [("learn", "Learn"), ("read", "Read"), ("watch", "Watch"), ("listen", "Listen")]
TYPE_ORDER = ["website", "app", "newsletter", "youtube", "bilibili", "podcast"]
TYPE_LABEL = {"website": "Websites", "app": "Apps", "newsletter": "Newsletters",
              "youtube": "YouTube", "bilibili": "Bilibili", "podcast": "Podcasts"}
TYPE_SINGULAR = {"website": "Website", "app": "App", "newsletter": "Newsletter",
                 "youtube": "YouTube", "bilibili": "Bilibili", "podcast": "Podcast"}
TYPE_ICON = {"website": "globe", "app": "smartphone", "newsletter": "mail",
             "youtube": "youtube", "bilibili": "tv", "podcast": "podcast"}
SCRIPT_LABEL = {"simplified": "简", "traditional": "繁", "both": "简繁"}
REGION_LABEL = {"cn": "CN", "tw": "TW", "hk": "HK", "sg": "SG", "my": "MY", "global": "Global"}
UI_ICONS = ["search", "github", "braces", "plus"]


# ── shared helpers ──────────────────────────────────────────────────────────

def gh_anchor(title):
    """GitHub's heading anchor: lowercase, drop punctuation, spaces to hyphens."""
    return re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")


def level_label(levels):
    if len(levels) == 3:
        return "All levels"
    names = [l.capitalize() for l in levels]
    return f"{names[0]}–{names[-1]}" if len(names) > 1 else names[0]


def meta_parts(r):
    """Short facts shown after each entry (the learner flag is rendered separately)."""
    parts = [level_label(r["level"]), SCRIPT_LABEL[r["script"]], REGION_LABEL[r["region"]]]
    if r["dialect"] == "cantonese":
        parts.append("Cantonese")
    if r["language"] != "zh":
        parts.append("English" if r["language"] == "en" else "Bilingual")
    if r["pricing"] != "free":
        parts.append(r["pricing"].capitalize())
    if r.get("subtitles"):
        text = "Transcripts" if r["type"] == "podcast" else "Subtitles"
        parts.append(text if r["subtitles"] == "free" else f"{text} (paid)")
    if r["login"] == "partial":
        parts.append("Some content needs login")
    elif r["login"] == "required":
        parts.append("Login required")
    return parts


def by_type(items):
    groups = {}
    for r in items:
        groups.setdefault(r["type"], []).append(r)
    return [(t, groups[t]) for t in TYPE_ORDER if t in groups]


def icon_source(name):
    return (ICON_DIR / f"{name}.svg").read_text(encoding="utf-8")


def icon_inner(name):
    svg = re.sub(r"<!--.*?-->", "", icon_source(name), flags=re.S)
    return re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1).strip()


# ── README ──────────────────────────────────────────────────────────────────

def readme_icons(cats):
    """Grey copies of the icons the README uses, keyed by repo-relative path."""
    names = {c["web_icon"] for c in cats} | set(TYPE_ICON.values())
    out = {}
    for n in sorted(names):
        svg = re.sub(r"<!--.*?-->\s*", "", icon_source(n), flags=re.S)
        out[f"{README_ICON_DIR}/{n}.svg"] = svg.replace('stroke="currentColor"', f'stroke="{README_ICON_COLOR}"')
    return out


def md_icon(name, size=16):
    return f'<img src="{README_ICON_DIR}/{name}.svg" width="{size}" height="{size}" alt="">'


def md_escape(s):
    return s.replace("[", "\\[").replace("]", "\\]")


def render_markdown(cats, by_cat):
    total = sum(len(v) for v in by_cat.values())
    out = [BEGIN, "", "## Contents", ""]
    for gid, gname in GROUPS:
        out.append(f"- **[{gname}](#{gh_anchor(gname)})**")
        for c in (c for c in cats if c["group"] == gid):
            out.append(f"  - {md_icon(c['web_icon'], 14)} [{c['name']}](#{gh_anchor(c['name'])}) · {len(by_cat.get(c['id'], []))}")
    picks = sum(r["recommended"] for v in by_cat.values() for r in v)
    out += ["", f"**{total} resources, {picks} picks.** After each entry: **Pick** for well-known, free resources that open "
            "without an account, *For learners* when it is made for learners, then level · 简 simplified / 繁 traditional · "
            "region · language if not all Chinese · pricing if not free · Chinese subtitles or transcripts as text · login needs.", ""]

    for gid, gname in GROUPS:
        out += [f"## {gname}", ""]
        for c in (c for c in cats if c["group"] == gid):
            items = by_cat.get(c["id"], [])
            out += [f"### {c['name']}", "", f"{c['name_zh']} · {c['description']}", ""]
            for t, rs in by_type(items):
                out += [f"{md_icon(TYPE_ICON[t])} **{TYPE_LABEL[t]}**", ""]
                for r in rs:
                    meta = (["**Pick**"] if r["recommended"] else []) + (["*For learners*"] if r["for_learners"] else []) + meta_parts(r)
                    out.append(f"- [{md_escape(r['name'])}]({r['url']}) - {r['description']} <sub>{' · '.join(meta)}</sub>")
                out.append("")
            out += ["[Back to contents](#contents)", ""]
    out.append(END)
    return "\n".join(out)


def splice_readme(current, generated):
    """Replace the generated block in README.md, keeping the hand-written text around it."""
    if BEGIN in current and END in current:
        head, rest = current.split(BEGIN, 1)
        return head + generated + rest.split(END, 1)[1]
    return current.rstrip() + "\n\n" + generated + "\n"


# ── GitHub Pages site ───────────────────────────────────────────────────────

SITE_TEMPLATE = Path(__file__).resolve().parent / "site_template.html"
SITE_ICONS = {"search", "github", "plus", "braces", "x", "external-link", "graduation-cap", "book-open", "clapperboard", "headphones"}
GROUP_INFO = {
    "learn": ("graduation-cap", "Lessons, graded readers, dictionaries and tools made for learners."),
    "read": ("book-open", "News, novels, comics and the sites native speakers read every day."),
    "watch": ("clapperboard", "Dramas, vlogs, cooking, comedy, animation and kids' shows."),
    "listen": ("headphones", "Music, podcasts, radio and audiobooks."),
}

# Quick-start buttons under the search box: label -> filter state.
PRESETS = [
    ("Picks", {"pick": "1"}),
    ("Beginner friendly", {"level": "beginner", "learner": "1"}),
    ("Podcasts for learners", {"cat": "learn_podcast"}),
    ("Graded reading", {"cat": "graded_reading"}),
    ("Native YouTube", {"type": "youtube", "level": "advanced"}),
    ("Taiwan", {"region": "tw"}),
    ("Kids' shows", {"cat": "kids"}),
]


def ic(name, cls="ic"):
    return f'<svg class="{cls}" aria-hidden="true"><use href="#i-{name}"/></svg>'


def logo_url(r):
    """A small real logo for the card: channel avatar, podcast artwork, or the site's favicon."""
    img = r.get("image")
    if img and r["type"] == "youtube":
        return re.sub(r"=s\d+", "=s88", img)
    if img and r["type"] == "podcast":
        return re.sub(r"\d+x\d+bb", "100x100bb", img)
    if img and r["type"] == "bilibili":
        return img + "@96w_96h_1c.webp"
    host = re.match(r"https?://([^/]+)", r["url"]).group(1)
    return f"https://www.google.com/s2/favicons?domain={host}&sz=64"


def card(r, esc):
    search = " ".join([r["name"], r["description"], " ".join(r["tags"]), r["id"], TYPE_LABEL[r["type"]]]).lower()
    attrs = (f'data-cat="{r["category"]}" data-type="{r["type"]}" data-level="{" ".join(r["level"])}" '
             f'data-script="{r["script"]}" data-region="{r["region"]}" data-learner="{int(r["for_learners"])}" '
             f'data-pick="{int(r["recommended"])}" data-login="{r["login"]}" data-s="{esc(search)}"')
    facts = " · ".join(esc(p) for p in meta_parts(r))
    learner = ('<span class="pick">Pick</span>' if r["recommended"] else "") + \
        ('<span class="learner">For learners</span>' if r["for_learners"] else "")
    initial = esc(r["name"].strip()[0].upper())
    return (
        f'<article class="card" {attrs}><a href="{esc(r["url"])}" target="_blank" rel="noopener">'
        f'<div class="card-head"><span class="logo"><b>{initial}</b>'
        f'<img src="{esc(logo_url(r))}" alt="" loading="lazy" decoding="async" referrerpolicy="no-referrer" '
        f'onload="lg(this)" onerror="lg(this,1)"></span><div class="title"><h3>{esc(r["name"])}</h3>'
        f'<span class="kind">{ic(TYPE_ICON[r["type"]])}{TYPE_SINGULAR[r["type"]]}</span></div>'
        f'{ic("external-link", "ic go")}</div>'
        f'<p class="desc">{esc(r["description"])}</p>'
        f'<p class="facts">{learner}<span>{facts}</span></p></a></article>')


def render_html(cats, by_cat, data_version):
    esc = html.escape
    total = sum(len(v) for v in by_cat.values())
    used = SITE_ICONS | set(TYPE_ICON.values())
    sprite = "".join(f'<symbol id="i-{n}" viewBox="0 0 24 24">{icon_inner(n)}</symbol>' for n in sorted(used))
    regions = len({r["region"] for v in by_cat.values() for r in v})

    side, chips, sections = [], [], []
    for gid, gname in GROUPS:
        gicon, gdesc = GROUP_INFO[gid]
        gcount = sum(len(by_cat.get(c["id"], [])) for c in cats if c["group"] == gid)
        side.append(f'<p class="side-group g-{gid}" data-group-label="{gid}"><i></i>{gname}</p>')
        sections.append(
            f'<div class="group-head g-{gid}" data-group-head="{gid}"><span class="gicon">{ic(gicon)}</span>'
            f'<div><h2>{gname}</h2><p>{esc(gdesc)}</p></div><span class="gcount" data-group-count>{gcount}</span></div>')
        for c in (c for c in cats if c["group"] == gid):
            items = by_cat.get(c["id"], [])
            side.append(f'<button type="button" class="g-{gid}" data-cat-btn="{c["id"]}" data-group="{gid}">'
                        f'<span>{esc(c["name"])}</span><span class="count">{len(items)}</span></button>')
            chips.append(f'<button type="button" class="g-{gid}" data-cat-btn="{c["id"]}" data-group="{gid}">{esc(c["name"])}'
                         f' <span class="count">{len(items)}</span></button>')
            sections.append(
                f'<section id="{c["id"]}" class="g-{gid}" data-section="{c["id"]}" data-group="{gid}">'
                f'<div class="sec-head"><h2>{esc(c["name"])}<span class="zh">{esc(c["name_zh"])}</span></h2>'
                f'<span class="count" data-sec-count>{len(items)}</span></div>'
                f'<p class="sec-desc">{esc(c["description"])}</p>'
                f'<div class="grid">{"".join(card(r, esc) for t, rs in by_type(items) for r in rs)}</div></section>')

    presets = "".join(f'<button type="button" data-preset=\'{html.escape(json.dumps(state), quote=True)}\'>{esc(label)}</button>'
                      for label, state in PRESETS)
    tabs = '<button type="button" data-tab="" class="on">All</button>' + "".join(
        f'<button type="button" class="g-{gid}" data-tab="{gid}"><i></i>{gname}</button>' for gid, gname in GROUPS)

    page = SITE_TEMPLATE.read_text(encoding="utf-8")
    for key, value in {
        "%%TOTAL%%": str(total), "%%NCATS%%": str(len(cats)), "%%NREGIONS%%": str(regions),
        "%%VERSION%%": data_version, "%%REPO%%": REPO_URL, "%%SPRITE%%": sprite,
        "%%SIDE%%": "\n".join(side), "%%CHIPS%%": "".join(chips), "%%SECTIONS%%": "\n".join(sections),
        "%%PRESETS%%": presets, "%%TABS%%": tabs,
        "%%IC_SEARCH%%": ic("search"), "%%IC_GITHUB%%": ic("github"), "%%IC_PLUS%%": ic("plus"),
        "%%IC_BRACES%%": ic("braces"), "%%IC_X%%": ic("x"),
    }.items():
        page = page.replace(key, value)
    return page
